def esc(value) -> str:
    return html.escape(str(value), quote=True)


def load(path: Path):
    return json.loads(path.read_text(encoding="utf-8"))


class Page:
    """Tiny HTML writer. `prefix` is the relative path from this page to the repository root."""

    def __init__(self, rel_name: str, prefix: str, title: str, eyebrow: str, h1: str, lead: str):
        self.rel_name, self.prefix = rel_name, prefix
        self.title, self.eyebrow, self.h1, self.lead = title, eyebrow, h1, lead
        self.parts: list[str] = []

    def add(self, *chunks: str) -> None:
        self.parts.extend(chunks)

    def render(self) -> str:
        in_cat = self.rel_name.startswith("categories/")
        nav_parts = []
        for href, label in NAV:
            target = ("../" if in_cat else "") + href
            current = href == self.rel_name or (in_cat and href == "requirements.html")
            aria = ' aria-current="page"' if current else ""
            nav_parts.append(f'<a href="{esc(target)}"{aria}>{esc(label)}</a>')
        nav = "".join(nav_parts)
        head = f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>{esc(self.title)} · NFL review desk</title>
<style>{CSS}</style>
</head>
<body>
<header class="top"><div class="wrap">
<a class="brand" href="{esc(self.prefix)}nfl-review-1c6816a0/site/index.html">NFL review desk</a>
<nav aria-label="Pages">{nav}</nav>
</div></header>
<main class="wrap">
<p class="eyebrow">{esc(self.eyebrow)}</p>
<h1>{esc(self.h1)}</h1>
<p class="lead">{esc(self.lead)}</p>
"""
        foot = f"""
<p class="foot">Generated by <code>nfl-review-1c6816a0/build.py</code> from committed files only. Session {esc(SESSION)}. Reads dated {READ_ON}. Not legal advice. Not a betting recommendation.</p>
</main>
</body>
</html>
"""
        return head + "\n".join(self.parts) + foot


