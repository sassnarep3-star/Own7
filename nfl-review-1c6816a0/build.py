def build(check: bool) -> int:
    pages = build_pages()
    manifest = {"schema": "nfl-review-1c6816a0/manifest/1", "site_root": "nfl-review-1c6816a0/site",
                "pages": sorted(pages)}
    audit = {
        "schema": "nfl-review-1c6816a0/audit/1",
        "session": SESSION,
        "read_on": READ_ON,
        "pages": sorted(pages),
        "note": "Counts computed from committed files. Statuses are the register's own; see flagged.html.",
    }
    outputs = {SITE / name: text for name, text in pages.items()}
    outputs[SITE / "manifest.json"] = json.dumps(manifest, indent=2) + "\n"
    outputs[DATA / "audit.json"] = json.dumps(audit, indent=2) + "\n"
    if check:
        stale = [str(path.relative_to(ROOT)) for path, text in outputs.items()
                 if not path.exists() or path.read_text(encoding="utf-8") != text]
        if stale:
            print("stale outputs (run build.py):\n  " + "\n  ".join(stale), file=sys.stderr)
            return 1
        print(f"build reproduces byte-identically ({len(outputs)} files)")
        return 0
    for path, text in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
    print(f"wrote {len(pages)} pages to {SITE.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(build(check="--check" in sys.argv[1:]))
