def club_depth_url(code):
    """Chart URL the depth desks cite for a club (first captured value)."""
    key = "AZ" if code == "ARI" else code
    for rel in (C.AVAIL_DEPTH, C.SKILL_DEPTH):
        for r in C.load_csv(rel):
            if r["club_abbr"] == key and r.get("source_url"):
                return r["source_url"]
    return None


def existing_registry():
    """URL -> ID for rows already in research/sources.json (excluding this desk's B77 rows).

    Where a URL is already registered, this desk reuses that ID and adds no row. Two IDs for one URL
    would change what other desks' pages resolve to (nfl-pricing maps URLs to IDs)."""
    out = {}
    for r in json.loads(SOURCES_JSON.read_text(encoding="utf-8")):
        if not r["id"].startswith("B77-"):
            out[r["url"]] = r["id"]
    return out


class Reg(dict):
    """Source key -> (id, url, record). Repo files and club depth charts are registered on first use;
    repo IDs are numbered in sorted path order by finalize(), so the output is deterministic.
    record is None when the ID already exists in research/sources.json (no new row is written)."""

    def __init__(self):
        super().__init__()
        self.existing = existing_registry()
        for key, (url, title, authority, scope, access) in T.SOURCE_DEFS.items():
            if url in self.existing:
                self[key] = (self.existing[url], url, None)
                continue
            self[key] = (f"B77-{key.upper()}", url, {
                "publisher": "NFL.com" if "nfl.com" in url else "Baltimore Ravens (club website)",
                "title": title, "url": url, "kind": "Official NFL page" if "nfl.com" in url else "Club website",
                "authority": authority, "scope": scope, "checked_on": CHECKED, "access": access,
                "status": "Content checked"})
        self.repo_keys = set()

    def ensure(self, key):
        if key in self:
            return self[key]
        if key.startswith("repo:"):
            if REPO_URL + key[5:] in self.existing:
                self[key] = (self.existing[REPO_URL + key[5:]], REPO_URL + key[5:], None)
                return self[key]
            self.repo_keys.add(key)
            self[key] = ("PENDING", REPO_URL + key[5:], None)
        elif key.startswith("depth:"):
            code = key[6:]
            url = club_depth_url(code)
            if not url:
                return None
            name = T.CLUBS.get(code, code)
            if url in self.existing:
                self[key] = (self.existing[url], url, None)
                return self[key]
            self[key] = (f"B77-DEPTH-{code}", url, {
                "publisher": f"{name} (club website)", "title": f"{name} depth chart", "url": url,
                "kind": "Club website", "authority": "Club website (not NFL.com)",
                "scope": "Depth chart as captured in the depth desk CSV (chart date given in the depth table)",
                "checked_on": CHECKED, "access": "Captured by the depth desk; rendered text, not an HTTP-status attestation",
                "status": "Content checked"})
        else:
            raise KeyError(f"unknown source key {key}")
        return self[key]

    def finalize(self):
        for i, key in enumerate(sorted(self.repo_keys), start=1):
            if self[key][2] is None and self[key][0] != "PENDING":
                continue
            url = self[key][1]
            p = key[5:]
            self[key] = (f"B77-R{i:02d}", url, {
                "publisher": "Own7 repository (this project)", "title": p, "url": url,
                "kind": "Repository artifact (not an external official source)",
                "authority": "Repository file on main; not an external official source",
                "scope": "File as present on main at build time; facts computed from it by nfl-brief-77b1/build.py",
                "checked_on": CHECKED, "access": "Repository file read by the build; no network",
                "status": "Repository artifact"})


