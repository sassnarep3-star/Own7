def sources_registry_rows(smap):
    rows = []
    for key, (rid, url, rec) in sorted(smap.items(), key=lambda kv: kv[1][0]):
        if rec is None:
            continue  # ID already registered by another desk; no new row
        rows.append({"id": rid, **{k: v for k, v in rec.items() if k != "url"}, "url": url})
    return rows


def write_registry(smap):
    """Merge B77-* rows into research/sources.json; keep every other row untouched and in order."""
    rows = json.loads(SOURCES_JSON.read_text(encoding="utf-8"))
    keep = [r for r in rows if not r["id"].startswith("B77-")]
    new = sources_registry_rows(smap)
    out = keep + new
    text = json.dumps(out, ensure_ascii=False, indent=1) + "\n"  # the registry's own format (indent=1)
    old = SOURCES_JSON.read_text(encoding="utf-8")
    if old != text:
        SOURCES_JSON.write_text(text, encoding="utf-8")
    return len(new)


def write_check_site_hosts(smap):
    """Maintain a marked SOURCE_HOSTS block in scripts/check_site.py for the B77-* IDs."""
    entries = {rid: url.split("/")[2] for _, (rid, url, rec) in smap.items() if rec is not None}
    body = "SOURCE_HOSTS.update({\n" + "".join(f"    {json.dumps(k)}: {json.dumps(v)},\n" for k, v in sorted(entries.items())) + "})\n"
    block = f"{BEGIN}\n{body}{END}\n"
    text = CHECK_SITE.read_text(encoding="utf-8")
    if BEGIN in text:
        pre, rest = text.split(BEGIN, 1)
        _, post = rest.split(END + "\n", 1)
        new = pre + block + post
    else:
        anchor = "# NFL research lab (session arena/a4e560bc-own7)"
        new = text.replace(anchor, block + "\n" + anchor, 1)
        if new == text:
            raise SystemExit("check_site.py anchor not found")
    if new != text:
        CHECK_SITE.write_text(new, encoding="utf-8")


# ---------- HTML helpers ----------

def e(x):
    return html.escape(str(x), quote=True)


def link(url, label):
    return f'<a href="{e(url)}">{e(label)}</a>'


def cell(v, empty=False):
    if empty or v in (None, ""):
        return '<td data-empty="true"></td>'
    return f"<td>{v if isinstance(v, Raw) else e(v)}</td>"


class Raw(str):
    """Pre-escaped HTML fragment."""


def table(caption, headers, rows):
    """rows: list of (ids, cells, source_links). Every row gets data-source-ids and links to its sources."""
    out = [f'<table><caption>{e(caption)}</caption><thead><tr>']
    out += [f'<th scope="col">{e(h)}</th>' for h in headers]
    out.append('</tr></thead><tbody>')
    for ids, cells, links in rows:
        out.append(f'<tr data-source-ids="{e(" ".join(ids))}">')
        for c in cells:
            if isinstance(c, tuple) and c and c[0] == "EMPTY":
                out.append('<td data-empty="true"></td>')
            else:
                out.append(cell(c))
        out.append(f'<td>{" · ".join(links)}</td></tr>')
    out.append('</tbody></table>')
    return "\n".join(out)


