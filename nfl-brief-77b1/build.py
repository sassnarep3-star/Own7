def src_links(smap, keys):
    """Links for a row, one per source key (deduplicated, order kept)."""
    seen, out = set(), []
    for k in keys:
        if smap.ensure(k) is None:
            continue
        if k in smap and smap[k][0] not in seen:
            seen.add(smap[k][0])
            label = {"nfl-injuries": "NFL.com injuries", "nfl-trades": "NFL.com transactions",
                     "nfl-reserve": "NFL.com reserve list", "bal-depth": "Ravens depth chart"}.get(k)
            if label is None:
                label = ("Repo: " + k[5:]) if k.startswith("repo:") else ("Chart: " + k[6:])
            out.append(link(smap[k][1], label))
    return out


def ids_for(smap, keys):
    out = []
    for k in keys:
        entry = smap.ensure(k)
        if entry is not None and entry[0] not in out:
            out.append(entry[0])
    return out


