def check_links(pages):
    """Internal link and table-row self-check (check_site.py is the authority; this catches errors earlier)."""
    errors = []
    names = set(pages)
    for name, text in pages.items():
        for href in re.findall(r'href="([^"]+)"', text):
            if href.startswith("http") or href.startswith("#"):
                continue
            if href not in names and href not in ("style.css",):
                errors.append(f"{name}: unresolved {href}")
        if text.count("<h1>") != 1 or text.count("<main") != 1:
            errors.append(f"{name}: document semantics")
    return errors


