def build() -> dict:
    rows = []
    for rid, text, status, gate, clearing, evidence in RAW + EXTRA:
        rows.append({
            "id": rid, "requirement": text, "status": status, "gate": gate,
            "clearing_number": clearing, "evidence": evidence,
            "source_ids": ["REPO"],
        })
    ids = [r["id"] for r in rows]
    assert len(ids) == len(set(ids)), "duplicate requirement id"
    assert all(r["requirement"].strip() for r in rows)
    # A requirement may not be `met` while its own gate is a hard blocker.
    for r in rows:
        if r["status"] == "met":
            assert r["gate"].startswith("none"), f"{r['id']} marked met while gated"
        assert r["gate"].strip() and r["clearing_number"].strip(), f"{r['id']} missing gate/clearing number"
    counts = {k: sum(1 for r in rows if r["status"] == k) for k in ("met", "partial", "blocked", "rejected")}
    assert sum(counts.values()) == len(rows)
    return {
        "schema_version": 1,
        "read": "2026-11-17",
        "note": ("Every line of the brief is one row, transcribed verbatim. Status, gate and clearing "
                 "number are this desk's assessment and name the artefact a reviewer can open. A row is "
                 "never met on the strength of a page existing."),
        "counts": counts,
        "requirements": rows,
        "gates": [{"id": g, "name": n, "statement": s, "clears_when": c} for g, n, s, c in GATES],
    }


def main() -> int:
    DATA.mkdir(exist_ok=True)
    payload = build()
    text = json.dumps(payload, indent=2, ensure_ascii=False) + "\n"
    target = DATA / "requirements.json"
    if "--check" in sys.argv:
        if not target.exists() or target.read_text() != text:
            raise SystemExit("requirements.json is stale: re-run without --check")
        print(f"OK: {len(payload['requirements'])} requirements, {payload['counts']}")
        return 0
    target.write_text(text)
    print(f"Wrote {target.relative_to(REPO)}: {len(payload['requirements'])} requirements, {payload['counts']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
